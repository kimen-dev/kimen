#!/usr/bin/env node
import { access, mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  discoverComponents,
  FROZEN_LEGACY_ROOT,
} from '../../../scripts/lib/component-inventory.mjs';

import { RUNTIME_CHUNK } from './component-chunk-names.mjs';

const templatePath = new URL('loader-template.js.txt', import.meta.url);
const generated = '// Generated by scripts/write-loader.mjs.\n';
const observeDeclaration = `/** Watches an application-owned shadow root or element and awaits its existing definitions. */
export declare function observeRoot(root: ShadowRoot | Element): Promise<void>;
`;

export function runtimeExportName(barrel) {
  const exports = /export\s*\{([^}]+)\}\s*from\s*['"]\.\/stencil-client\.js['"]/u.exec(barrel);
  const entry = exports?.[1]
    .split(',')
    .map((part) => part.trim().split(/\s+as\s+/u))
    .find(([local, exported = local]) => exported === 'setNonce');
  if (entry === undefined || !/^[$\w]+$/u.test(entry[0])) {
    throw new Error(
      `write-loader: dist/components/index.js does not re-export setNonce from ./${RUNTIME_CHUNK}`,
    );
  }
  return entry[0];
}

export async function writeLoader({ packageRoot, components, values }) {
  const loader = join(packageRoot, 'loader');
  const registry = join(loader, 'register');
  const declarations = join(loader, 'index.d.ts');
  const dist = join(packageRoot, 'dist');
  const [template, barrel, types] = await Promise.all([
    readFile(templatePath, 'utf8'),
    readFile(join(dist, 'components/index.js'), 'utf8'),
    readFile(declarations, 'utf8'),
  ]);
  const nonce = runtimeExportName(barrel);
  await Promise.all([
    access(join(dist, 'components', RUNTIME_CHUNK)),
    ...components.map(({ distModule }) => access(join(packageRoot, distModule))),
  ]);

  // A class-only entry groups the public module with its implementation and
  // private dependencies where the bundler can prove they share an importer.
  // Discovering the children in the DOM keeps conditional children independent.
  const names = new Set(components.map(({ tag }) => `${tag}.js`));
  await mkdir(registry, { recursive: true });
  for (const name of await readdir(registry)) {
    if (!names.has(name)) await unlink(join(registry, name));
  }
  await Promise.all(
    components.map(({ tag, className, distModule }) =>
      writeFile(
        join(registry, `${tag}.js`),
        `${generated}export { ${className} as default } from ${JSON.stringify(`../../${distModule.slice(2)}`)};\n`,
      ),
    ),
  );

  const modules = components
    .map(({ tag }) => `  ${JSON.stringify(tag)}: () => import("./register/${tag}.js"),`)
    .join('\n');
  const facade = values
    .map(
      ({ name, replacement }) =>
        `export { ${name} } from "./components/${replacement.split('/').at(-1)}.js";`,
    )
    .join('\n');

  await Promise.all([
    writeFile(
      join(loader, 'index.js'),
      template.replace('  /* MODULES */', modules).replaceAll('/* NONCE */', nonce),
    ),
    writeFile(join(dist, 'index.js'), `${generated}${facade}\n`),
    writeFile(
      declarations,
      types.includes(observeDeclaration) ? types : `${types.trimEnd()}\n\n${observeDeclaration}`,
    ),
  ]);
}

async function main() {
  const packageRoot = fileURLToPath(new URL('..', import.meta.url));
  const workspaceRoot = fileURLToPath(new URL('../../..', import.meta.url));
  const components = await discoverComponents({ workspaceRoot });
  await writeLoader({ packageRoot, components, values: FROZEN_LEGACY_ROOT.values });
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
