import { mkdir, writeFile } from 'node:fs/promises';
import { brotliCompressSync } from 'node:zlib';

import { componentSourceOf, declaredNames } from './component-sheets.mjs';

const CUSTOM_PROPERTY = /\bvar\(\s*(--ki-[a-z0-9-]+)/giu;
const TYPE_FLAGS = { color: 1, dimension: 2, duration: 3, time: 3 };

// Group names with identical flags, factoring out their common hyphenated
// prefixes. Each branch is [prefix, children]; an empty leaf names the prefix
// itself (e.g. both color-accent and color-accent-hover may exist).
function nameTree(names) {
  const groups = Map.groupBy(names, (name) => name.split('-', 1)[0]);
  return [...groups].map(([prefix, group]) =>
    group.length === 1
      ? group[0]
      : [prefix, nameTree(group.map((name) => name.slice(prefix.length + 1)))],
  );
}

export function packThemeCheckerData({ modes, tokens }) {
  const groups = Map.groupBy(tokens, ([, flags]) => flags);
  const packed = [
    modes,
    [...groups].map(([flags, rows]) => [flags, nameTree(rows.map(([name]) => name))]),
  ];
  return brotliCompressSync(JSON.stringify(packed)).toString('base64');
}

export async function writeThemeCheckerData({ sharedTokens, usage, baseModes, sheets }) {
  const byPath = new Map(sharedTokens.map((token) => [token.original.key, token]));
  // Style Dictionary leaves the type unset on untyped aliases such as
  // button.label-padding-inline. DTCG takes their type from the target.
  const typeOf = (token) => {
    if (token === undefined) return '';
    return token.$type ?? typeOf(byPath.get(token.original.$value));
  };
  const byName = new Map(sharedTokens.map((token) => [`--${token.name}`, token]));
  const names = new Set(sheets.flatMap((css) => [...declaredNames(css)]));
  const reads = new Set(
    sheets.flatMap((css) => [...css.matchAll(CUSTOM_PROPERTY)].map((m) => m[1])),
  );
  for (const { tokens } of usage.values()) {
    for (const name of tokens) {
      reads.add(name);
      // A component script can choose the suffix at runtime (spec 166).
      if (name.endsWith('-')) {
        for (const candidate of names) if (candidate.startsWith(name)) reads.add(candidate);
      }
    }
  }

  const data = {
    modes: baseModes.map(({ mode }) => mode),
    tokens: [...names]
      .filter((name) => name.startsWith('--ki-'))
      .sort()
      .map((name) => {
        const token = byName.get(name);
        const source = token?.filePath;
        const warn =
          !reads.has(name) &&
          (source === 'tokens/semantic.tokens.json' || componentSourceOf(source) !== null);
        // Bits 0–1: checked type. Bit 2: unread advisory. Bits 3+: modes.
        const modes = baseModes.reduce((mask, { declarations }, index) => {
          return declarations.has(name) ? mask | (1 << (index + 3)) : mask;
        }, 0);
        return [
          name.slice('--ki-'.length),
          (TYPE_FLAGS[typeOf(token)] ?? 0) | (warn ? 4 : 0) | modes,
        ];
      }),
  };
  const generated = new URL('../generated/', import.meta.url);
  await mkdir(generated, { recursive: true });
  await writeFile(
    new URL('theme-checker-data.json', generated),
    [
      '{',
      `  "modes": ${JSON.stringify(data.modes)},`,
      '  "tokens": [',
      data.tokens.map((entry) => `    ${JSON.stringify(entry)}`).join(',\n'),
      '  ]',
      '}',
      '',
    ].join('\n'),
  );
  // The checked-in inventory is diffable. The installed checker and the
  // self-contained MCP bundle share this compact build of that inventory.
  const compressed = packThemeCheckerData(data);
  await writeFile(
    new URL('../dist/theme-checker-data.mjs', import.meta.url),
    `// Generated by the token build. See generated/theme-checker-data.json.\nexport default '${compressed}';\n`,
  );
}
