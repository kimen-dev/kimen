// Generates the self-contained MCP Apps surface documents (spec 030 FR-002,
// FR-007, FR-011, FR-013; spec 165) into src/generated: the full document,
// which registers every catalog component, and one document per published
// profile (scripts/surface-profiles.mjs), each registering only its subset
// and validating against that subset alone. scripts/surface-documents.mjs
// builds them; this script writes the modules that carry them.
//
// Deterministic: a pure transform of the dependency builds — no network, no
// date, no randomness, no machine path — so regeneration is byte-identical and
// a host's cached audit stays valid (S2). `--check` rebuilds in memory and
// fails unless the result equals the packaged documents.
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, gzipSync } from 'node:zlib';

import { generateSurfaceDocument } from './surface-documents.mjs';
import { SURFACE_PROFILES } from './surface-profiles.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const outFile = resolve(packageRoot, 'src/generated/surface-document.ts');
const inventoryFile = resolve(packageRoot, 'src/generated/surface-packages.json');
const profileFile = (name) => resolve(packageRoot, `src/generated/surface-profile-${name}.ts`);

const size = (html, count) => {
  const bytes = Buffer.from(html, 'utf8');
  return `${bytes.length} B raw, ${gzipSync(bytes, { level: 9 }).length} B gzip, ${brotliCompressSync(bytes).length} B brotli, ${count} components`;
};

const { html, packages, tags } = await generateSurfaceDocument();
const inventory = `${JSON.stringify(packages, null, 2)}\n`;
const module = `/**
 * GENERATED by scripts/generate-surface.mjs — do not edit.
 *
 * The self-contained MCP Apps surface document (spec 030): one HTML document
 * with every catalog component definition, the guarded renderer and the
 * default token stylesheet inlined, and a content policy that references no
 * external origin and admits only that script and that stylesheet, by digest.
 * Regeneration is byte-identical (S2).
 */
export const SURFACE_DOCUMENT = ${JSON.stringify(html)};
`;

// One module per profile (spec 165). Its constant is declared as a
// `SurfaceProfile`, never inferred: a `const` initialized with a literal is
// typed as that literal, and the declaration would repeat the whole document.
const fullInventory = new Set(packages.map(({ name, version }) => `${name}@${version}`));
const profiles = [];
for (const [name, profile] of Object.entries(SURFACE_PROFILES)) {
  const generated = await generateSurfaceDocument({ subset: profile.components });
  // The full document's inventory feeds the bundled-package notices; a
  // profile may only bundle what it already lists.
  const extra = generated.packages.filter(
    ({ name: pkg, version }) => !fullInventory.has(`${pkg}@${version}`),
  );
  if (extra.length > 0) {
    throw new Error(
      `adapter-mcp-apps: the "${name}" profile bundles packages the full document does not: ${extra.map((pkg) => pkg.name).join(', ')}`,
    );
  }
  const constant = `${name.toUpperCase()}_PROFILE`;
  profiles.push({
    file: profileFile(name),
    module: `/**
 * GENERATED by scripts/generate-surface.mjs — do not edit.
 *
 * The «${name}» surface profile (spec 165): a self-contained MCP Apps document
 * that registers only the components of its subset, validates against that
 * subset alone and carries a content policy of its own. \`components\` is the
 * effective subset, the only components a spec may name in it.
 */
import type { SurfaceProfile } from '../surface.js';

export const ${constant}: SurfaceProfile = Object.freeze({
  components: Object.freeze(${JSON.stringify(generated.components)}),
  document: ${JSON.stringify(generated.html)},
  name: ${JSON.stringify(name)},
});
`,
    size: size(generated.html, generated.tags.length),
    name,
  });
}

if (process.argv.includes('--check')) {
  const packaged = existsSync(outFile) ? await readFile(outFile, 'utf8') : undefined;
  const packagedInventory = existsSync(inventoryFile)
    ? await readFile(inventoryFile, 'utf8')
    : undefined;
  if (packaged !== module || packagedInventory !== inventory) {
    console.error(
      'adapter-mcp-apps: the generated surface document or bundle inventory is stale — rebuild the package',
    );
    process.exit(1);
  }
  for (const profile of profiles) {
    const packagedProfile = existsSync(profile.file)
      ? await readFile(profile.file, 'utf8')
      : undefined;
    if (packagedProfile !== profile.module) {
      console.error(
        `adapter-mcp-apps: the generated «${profile.name}» profile document is stale — rebuild the package`,
      );
      process.exit(1);
    }
  }
  console.log(`adapter-mcp-apps: surface-document.ts is reproducible (${size(html, tags.length)})`);
  for (const profile of profiles) {
    console.log(
      `adapter-mcp-apps: surface-profile-${profile.name}.ts is reproducible (${profile.size})`,
    );
  }
} else {
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, module, 'utf8');
  await writeFile(inventoryFile, inventory, 'utf8');
  for (const profile of profiles) {
    await writeFile(profile.file, profile.module, 'utf8');
  }
  console.log(`adapter-mcp-apps: generated surface-document.ts (${size(html, tags.length)})`);
  for (const profile of profiles) {
    console.log(`adapter-mcp-apps: generated surface-profile-${profile.name}.ts (${profile.size})`);
  }
}
