#!/usr/bin/env node
// The lazy loader and the root facade, on the per-component modules (Art. I:
// a deterministic post-pass of the build; nothing it writes is edited by
// hand).
//
// `@kimen/elements/loader` registers every ki-* component a page shows and
// downloads each one's module the first time the page shows it. Stencil's
// own loader ran on its lazy build, a second compiled copy of every component
// (dist/esm, a third of the package with its maps). This pass writes the
// loader over dist/components instead, the modules the `@kimen/elements/<tag>`
// subpaths publish: `loader/index.js` names each component's module in a
// static `import()`, so every bundler emits one chunk per component, and the
// page imports a module when an element of its tag first reaches the
// document. Stencil still writes `loader/index.d.ts`, which this pass keeps:
// the loader's types do not change.
//
// The deprecated root facade (`dist/index.js`) re-exported the lazy build
// too. It now re-exports each frozen value from the component's own module.
//
// The pass refuses to guess: a component without its module, or a runtime
// that no longer names `setNonce`, stops the build.
import { access, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const RUNTIME = 'stencil-client.js';

/** The local name the runtime chunk exports `setNonce` as, read from the components barrel. */
export function runtimeExportName(barrel, name) {
  const match = /export\s*\{([^}]*)\}\s*from\s*"\.\/stencil-client\.js"/u.exec(barrel);
  const entry = match?.[1]
    .split(',')
    .map((part) => part.trim().split(/\s+as\s+/u))
    .find(([, exported]) => exported === name);
  if (entry === undefined) {
    throw new Error(
      `write-loader: dist/components/index.js does not re-export ${name} from ./${RUNTIME}`,
    );
  }
  return entry[0];
}

/** loader/index.js for `tags`, given the runtime's local name for setNonce. */
export function loaderModule(tags, nonceExport) {
  const modules = tags
    .map((tag) => `  '${tag}': () => import('../dist/components/${tag}.js'),`)
    .join('\n');
  return `// GENERATED by packages/elements/scripts/write-loader.mjs — never edit by hand.
// Registers each ki-* component the first time the page shows it, from the
// module its \`@kimen/elements/<tag>\` subpath publishes.
const modules = {
${modules}
};

let nonce;
let runtime;
const loadRuntime = () =>
  import('../dist/components/${RUNTIME}').then((module) => {
    runtime = module;
    if (nonce !== undefined) module.${nonceExport}(nonce);
    return module;
  });

/** The nonce of the styles the components add, before or after they load. */
export function setNonce(value) {
  nonce = value;
  runtime?.${nonceExport}(value);
}

const defined = new Map();
const define = (tag) => {
  let definition = defined.get(tag);
  if (definition === undefined) {
    definition = Promise.all([loadRuntime(), modules[tag]()]).then(([, module]) =>
      module.defineCustomElement(),
    );
    defined.set(tag, definition);
  }
  return definition;
};

let observer;

export async function defineCustomElements(_win, options = {}) {
  if (typeof window === 'undefined') return undefined;
  const excluded = new Set(options.exclude ?? []);
  const wanted = (tag) => Object.hasOwn(modules, tag) && !excluded.has(tag);
  const discover = (root) => {
    const definitions = [];
    if (root.matches(':not(:defined)') && wanted(root.localName)) {
      definitions.push(define(root.localName));
    }
    for (const element of root.querySelectorAll(':not(:defined)')) {
      if (wanted(element.localName)) definitions.push(define(element.localName));
    }
    return definitions;
  };
  observer?.disconnect();
  observer = new MutationObserver((records) => {
    for (const { addedNodes } of records) {
      for (const node of addedNodes) {
        if (node.nodeType === 1) void Promise.all(discover(node));
      }
    }
  });
  observer.observe(document.documentElement, { childList: true, subtree: true });
  await Promise.all(discover(document.documentElement));
}
`;
}
